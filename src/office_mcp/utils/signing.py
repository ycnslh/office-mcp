"""HMAC-signed download tokens for the ``/files/{token}`` endpoint.

Each token encodes ``(user_id, uri, expires_at)`` and is authenticated with
HMAC-SHA256. Clients holding a valid token can download the file; the
signing secret is NOT required at download time, so the URL alone
conveys the authorisation — that is the point when LibreChat's browser
UI needs to fetch a file generated by an MCP tool.

Security properties:
  - Token is per-file / per-user — cannot be used to access another user's
    scope or another file in the same scope.
  - Token expires after ``ttl_seconds`` (15 min default); replay after
    expiry yields HTTP 403.
  - Tampering with any field invalidates the HMAC.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import time
from dataclasses import dataclass


class InvalidTokenError(ValueError):
    """Token is malformed, expired, or its signature does not match."""


@dataclass(frozen=True, slots=True)
class TokenClaims:
    user_id: str
    uri: str
    expires_at: int
    #: Optional OAuth ``state`` (token-store key) that the download
    #: route uses to resolve a Microsoft Graph access token at request
    #: time. Absent on URLs minted for ``local://`` (no token needed)
    #: and on URLs minted before this field landed — the verify path
    #: tolerates both shapes.
    state: str | None = None


def sign(
    *,
    user_id: str,
    uri: str,
    secret: str,
    ttl_seconds: int = 900,
    state: str | None = None,
) -> str:
    """Return a URL-safe opaque token authorising a download.

    ``state`` is optional and only meaningful for cloud-backed URIs
    (e.g. ``od://``) where the download endpoint needs a per-user
    OAuth token to fetch bytes. Embedding it lets ``/files/{token}``
    look up the right access token without keeping any extra
    server-side mapping keyed by user.
    """
    if not secret:
        raise ValueError("signing secret must not be empty")
    claims: dict[str, str | int] = {
        "uid": user_id,
        "uri": uri,
        "exp": int(time.time()) + ttl_seconds,
    }
    if state is not None:
        claims["sta"] = state
    payload = json.dumps(claims, separators=(",", ":"), sort_keys=True).encode()
    mac = hmac.new(secret.encode(), payload, hashlib.sha256).digest()
    return (
        _b64encode(payload) + "." + _b64encode(mac)
    )


def verify(token: str, *, secret: str) -> TokenClaims:
    """Decode and authenticate ``token``; raise :class:`InvalidTokenError`."""
    if not secret:
        raise InvalidTokenError("signing is disabled on the server")
    try:
        payload_b64, sig_b64 = token.split(".", 1)
    except ValueError as exc:
        raise InvalidTokenError("malformed token") from exc

    try:
        payload = _b64decode(payload_b64)
        sig = _b64decode(sig_b64)
    except ValueError as exc:
        raise InvalidTokenError("bad base64 payload") from exc

    expected = hmac.new(secret.encode(), payload, hashlib.sha256).digest()
    if not hmac.compare_digest(sig, expected):
        raise InvalidTokenError("bad signature")

    try:
        claims = json.loads(payload)
    except json.JSONDecodeError as exc:
        raise InvalidTokenError("bad payload") from exc

    try:
        uid = str(claims["uid"])
        uri = str(claims["uri"])
        exp = int(claims["exp"])
    except (KeyError, TypeError, ValueError) as exc:
        raise InvalidTokenError("missing/invalid claims") from exc

    raw_state = claims.get("sta")
    state = str(raw_state) if raw_state is not None else None

    if exp < time.time():
        raise InvalidTokenError("expired")

    return TokenClaims(user_id=uid, uri=uri, expires_at=exp, state=state)


def _b64encode(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def _b64decode(data: str) -> bytes:
    padding = "=" * (-len(data) % 4)
    return base64.urlsafe_b64decode(data + padding)
